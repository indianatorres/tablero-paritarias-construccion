DATA_DIR = os.path.dirname(os.path.abspath(os.getcwd()))

@st.cache_data(ttl=600)
def cargar_salarios_excel():
    ruta = os.path.join(DATA_DIR, "boletin_de_informacion_estadistica_sobre_negociacion_colectiva-septiembre_26.xlsx")
    if not os.path.exists(ruta):
        return None, None
    try:
        import openpyxl
        wb = openpyxl.load_workbook(ruta, data_only=True)
        resultados = {}
        for cuadro, label in [("Cuadro 9", "Cat. Inferior"), ("Cuadro 10", "Cat. Representativa")]:
            ws = wb[cuadro]
            row3 = [c.value for c in list(ws.iter_rows(min_row=3, max_row=3))[0]]
            col_comercio = col_construccion = None
            for i, v in enumerate(row3):
                if v and "omercio" in str(v):
                    col_comercio = i
                if v and "onstrucci" in str(v):
                    col_construccion = i
            if col_comercio is None or col_construccion is None:
                continue
            datos = {"Período": [], "Construcción": [], "Comercio": []}
            start_row = 5 if cuadro == "Cuadro 10" else 4
            for row in ws.iter_rows(min_row=start_row, max_row=ws.max_row, values_only=False):
                fecha = row[0].value
                if not fecha or not hasattr(fecha, "year"):
                    continue
                if fecha.year < 2024:
                    continue
                datos["Período"].append(fecha.strftime("%Y-%m"))
                datos["Construcción"].append(row[col_construccion].value)
                datos["Comercio"].append(row[col_comercio].value)
            resultados[label] = pd.DataFrame(datos)
        return resultados.get("Cat. Inferior"), resultados.get("Cat. Representativa")
    except Exception:
        return None, None

