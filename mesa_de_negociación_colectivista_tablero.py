def calcular_acumulada(variaciones_mensuales):
    factor = 1.0
    for v in variaciones_mensuales:
        factor *= (1 + v / 100)
    return (factor - 1) * 100


def build_ipc_df():
    df = pd.DataFrame({
        "Período": list(IPC_MENSUAL.keys()),
        "Var_Mensual_Pct": list(IPC_MENSUAL.values()),
    })
    df["Fecha"] = pd.to_datetime(df["Período"] + "-01")
    df["Índice"] = df["Período"].map(IPC_INDICES)
    df["Var_Interanual_Pct"] = df["Período"].map(IPC_INTERANUAL)
    acum = []
    current_year = None
    year_vars = []
    for _, row in df.iterrows():
        yr = row["Fecha"].year
        if yr != current_year:
            current_year = yr
            year_vars = []
        year_vars.append(row["Var_Mensual_Pct"])
        acum.append(calcular_acumulada(year_vars))
    df["Acum_Anual_Pct"] = acum
    return df


def build_salarios_df():
    sal_excel_inf, sal_excel_rep = cargar_salarios_excel()
    if sal_excel_inf is not None and len(sal_excel_inf) > 0:
        df = sal_excel_inf.copy()
        df["Fuente"] = "Excel (Cuadro 9)"
    else:
        df = pd.DataFrame(SALARIOS_CAT_INFERIOR)
        df["Fuente"] = "Datos embebidos"
    df["Fecha"] = pd.to_datetime(df["Período"] + "-01")
    df = df.sort_values("Fecha").reset_index(drop=True)
    df["Var_Construccion_Pct"] = df["Construcción"].pct_change(12) * 100
    df["Var_Comercio_Pct"] = df["Comercio"].pct_change(12) * 100
    return df


def build_eil_df():
    return pd.DataFrame(EIL_SERIE_TRIMESTRAL)

